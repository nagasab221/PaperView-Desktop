// GUI subsystem: no console window on launch.
// Debug logs go through OutputDebugString (visible in DebugView / WinDbg).
#![windows_subsystem = "windows"]

use eframe::egui;
use paperview::app::ViewerApp;

fn main() -> eframe::Result<()> {
    // `paperview.exe some.pdf` opens the file straight away (the hook the
    // "Open with" association uses). --register / --unregister manage the
    // per-user .pdf association headlessly (for scripts and installers).
    let first_arg = std::env::args_os().nth(1);
    match first_arg.as_deref().and_then(|s| s.to_str()) {
        Some("--register") => {
            if let Err(e) = paperview::assoc::register() {
                eprintln!("register failed: {e}");
            }
            return Ok(());
        }
        Some("--unregister") => {
            if let Err(e) = paperview::assoc::unregister() {
                eprintln!("unregister failed: {e}");
            }
            return Ok(());
        }
        _ => {}
    }
    let initial_file = first_arg.map(std::path::PathBuf::from);

    // Raw 128×128 RGBA generated by scripts/make_icon.py — no image decoder
    // needed at runtime.
    let icon = egui::IconData {
        rgba: include_bytes!("../assets/icon_128.rgba").to_vec(),
        width: 128,
        height: 128,
    };

    // Debug builds: PAPERVIEW_SIZE=WxH fixes the window size (UI tests).
    #[cfg(debug_assertions)]
    let size = std::env::var("PAPERVIEW_SIZE")
        .ok()
        .and_then(|v| {
            let (w, h) = v.split_once('x')?;
            Some([w.parse().ok()?, h.parse().ok()?])
        })
        .unwrap_or([1100.0, 800.0]);
    #[cfg(not(debug_assertions))]
    let size = [1100.0, 800.0];

    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title("PaperView")
            // Matches the desktop entry's StartupWMClass, so Linux shells
            // show the right icon and group the windows.
            .with_app_id("paperview")
            .with_inner_size(size)
            .with_min_inner_size([480.0, 320.0])
            .with_icon(icon)
            // Start invisible; the first frame sends Visible(true) once
            // content has been painted, eliminating any startup flash.
            .with_visible(false),
        // Remember window size/position between sessions.
        persist_window: std::env::var_os("PAPERVIEW_SIZE").is_none(),
        // persist_window restores saved state (including visibility) before
        // the window is created. This hook runs after that, forcing the
        // window hidden again so it stays invisible until the first frame.
        window_builder: Some(Box::new(|vb| vb.with_visible(false))),
        ..Default::default()
    };

    eframe::run_native(
        "PaperView",
        options,
        Box::new(move |cc| Ok(Box::new(ViewerApp::new(cc, initial_file)))),
    )
}
